import React from 'react';
import {AbsoluteFill, interpolate, spring, useCurrentFrame, useVideoConfig} from 'remotion';
import {HEAD_FONT, BODY_FONT} from '../fonts';
import {Snd} from './Type';

const OUTLINE = (c: string, w = 6) =>
  [`-${w}px -${w}px 0`, `${w}px -${w}px 0`, `-${w}px ${w}px 0`, `${w}px ${w}px 0`, `0 ${w + 2}px 0`, `0 -${w}px 0`, `${w}px 0 0`, `-${w}px 0 0`].map((s) => `${s} ${c}`).join(',');

// Big headline text. Each word pops in with a spring, staggered; whole block can sit anywhere.
export const KText: React.FC<{
  text: string;
  at?: number;
  until?: number; // frame at which it fades out (optional)
  x?: number; // centre
  y?: number;
  size?: number;
  color?: string;
  stagger?: number;
  rotate?: number;
  highlight?: string[]; // words drawn in `accent`
  accent?: string;
}> = ({text, at = 0, until, x = 960, y = 540, size = 120, color = '#fff', stagger = 4, rotate = 0, highlight = [], accent = '#ffd23f'}) => {
  const frame = useCurrentFrame();
  const {fps} = useVideoConfig();
  const words = text.split(' ');
  const out = until ? interpolate(frame, [until - 8, until], [1, 0], {extrapolateLeft: 'clamp', extrapolateRight: 'clamp'}) : 1;
  if (frame < at || out <= 0) return null;
  return (
    <div style={{position: 'absolute', left: x, top: y, transform: `translate(-50%, -50%) rotate(${rotate}deg)`, opacity: out, textAlign: 'center', width: 1700}}>
      {words.map((_, i) => <Snd key={`s${i}`} file="pop_a" at={at + i * stagger} vol={0.2} rate={0.85 + i * 0.07} frames={12} />)}
      {words.map((w, i) => {
        const s = spring({frame: frame - at - i * stagger, fps, config: {damping: 9, stiffness: 180, mass: 0.7}});
        const isHi = highlight.some((h) => w.toLowerCase().replace(/[^a-z0-9]/g, '') === h.toLowerCase());
        return (
          <span
            key={i}
            style={{
              display: 'inline-block',
              margin: '0 0.24em',
              fontFamily: HEAD_FONT,
              fontSize: size,
              lineHeight: 1.05,
              color: isHi ? accent : color,
              textShadow: OUTLINE('#1a1210', Math.max(4, size / 22)),
              transform: `scale(${s}) translateY(${(1 - s) * 40}px)`,
              opacity: Math.min(1, s * 1.5),
            }}
          >
            {w}
          </span>
        );
      })}
    </div>
  );
};

export type CaptionWord = {word: string; start: number; end: number}; // seconds

// Word-by-word captions: shows a sliding window of words, current word highlighted.
// Feed it ElevenLabs word timestamps; until then pass `words` generated by `evenWords`.
export const Captions: React.FC<{words: CaptionWord[]; accent?: string; window?: number; bottom?: number}> = ({words, accent = '#ffd23f', window = 6, bottom = 90}) => {
  const frame = useCurrentFrame();
  const {fps} = useVideoConfig();
  const t = frame / fps;
  let cur = words.findIndex((w) => t >= w.start && t < w.end);
  if (cur < 0) cur = words.reduce((a, w, i) => (t >= w.end ? i : a), -1);
  if (cur < 0 || t > words[words.length - 1].end + 0.6) return null;
  const startIdx = Math.floor(cur / window) * window;
  const group = words.slice(startIdx, startIdx + window);
  if (t - words[Math.min(startIdx + window, words.length) - 1].end > 0.4) return null;
  return (
    <AbsoluteFill style={{justifyContent: 'flex-end', alignItems: 'center', paddingBottom: bottom, pointerEvents: 'none'}}>
      <div style={{maxWidth: 1600, textAlign: 'center'}}>
        {group.map((w, i) => {
          const active = startIdx + i === cur;
          const pop = active ? spring({frame: frame - Math.round(w.start * fps), fps, config: {damping: 10, stiffness: 250}}) : 1;
          return (
            <span key={startIdx + i} style={{display: 'inline-block', margin: '0 0.18em', fontFamily: BODY_FONT, fontWeight: 800, fontSize: 62, color: active ? accent : '#fff', textShadow: OUTLINE('#000', 4), transform: `scale(${active ? 1 + (1 - Math.min(pop, 1)) * -0.0 + 0.1 * Math.min(pop, 1) : 1})`}}>
              {w.word}
            </span>
          );
        })}
      </div>
    </AbsoluteFill>
  );
};

// Spreads a sentence evenly over [start, end] seconds. Placeholder until real timestamps exist.
export const evenWords = (text: string, start: number, end: number): CaptionWord[] => {
  const ws = text.split(' ');
  const step = (end - start) / ws.length;
  return ws.map((word, i) => ({word, start: start + i * step, end: start + (i + 1) * step}));
};

// Big slamming counter label, e.g. "DAY 5".
export const SlamLabel: React.FC<{text: string; at: number; x?: number; y?: number; size?: number; color?: string}> = ({text, at, x = 960, y = 200, size = 170, color = '#fff'}) => {
  const frame = useCurrentFrame();
  const {fps} = useVideoConfig();
  const t = frame - at;
  if (t < 0) return null;
  const s = spring({frame: t, fps, config: {damping: 7, stiffness: 220, mass: 0.8}});
  const scale = interpolate(s, [0, 1], [2.6, 1]);
  const o = interpolate(t, [0, 4], [0, 1], {extrapolateRight: 'clamp'});
  return (
    <div style={{position: 'absolute', left: x, top: y, transform: `translate(-50%, -50%) scale(${scale})`, opacity: o, fontFamily: HEAD_FONT, fontSize: size, color, textShadow: OUTLINE('#1a1210', 9), letterSpacing: 4}}>
      {text}
    </div>
  );
};
