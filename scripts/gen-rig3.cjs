// Packs the hand-authored SVG rigs (_reference/all_pose_rigs) into src/new/rig3data.ts and copies the clip library.
const fs = require('fs');
const D = '_reference/all_pose_rigs/';
const out = {};
for (const [k, f] of [['main', 'main_character.svg'], ['manager', 'manager_rig.svg'], ['mother', 'mother_rig.svg']]) {
  let s = fs.readFileSync(D + f, 'utf8');
  s = s.replace(/<\?xml[^>]*>/, '');
  const a = s.indexOf('<defs>'), b = s.indexOf('<g id="props"');
  let inner = s.slice(a, b);
  // personality pass: bigger, friendlier eyes (the approved PNG poses have large eyes)
  inner = inner.replace(/rx="7" ry="11"/g, 'rx="9.5" ry="13.5"').replace(/rx="6" ry="10"/g, 'rx="8" ry="12.5"').replace(/rx="8" ry="11"/g, 'rx="10" ry="13.5"').replace(/rx="8" ry="11"/g, 'rx="10" ry="13.5"')
    .replace(/<circle cx="(-?\d+)" cy="(-?\d+)" r="3" fill="#29221f"\/>/g, (m, x, y) => `<circle cx="${x}" cy="${y}" r="4.6" fill="#29221f"/>`)
    .replace(/<circle cx="(-?\d+)" cy="(-?\d+)" r="3.5" fill="#29221f"\/>/g, (m, x, y) => `<circle cx="${x}" cy="${y}" r="5" fill="#29221f"/>`);
  // mouthless twins of the face groups, used whenever an expression supplies its own mouth
  inner = inner.replace(/<g id="face-(front|three-quarter|profile)">([\s\S]*?)<\/g>/g, (m, nm, body) => {
    const k = body.lastIndexOf('<path');
    return m + '<g id="face-' + nm + '-nm">' + body.slice(0, k) + '</g>';
  });
  out[k] = inner;
}
const clips = JSON.parse(fs.readFileSync(D + 'animation_clips.json', 'utf8')).clips;
fs.writeFileSync('src/new/rig3data.ts', '// @ts-nocheck\n// GENERATED by scripts/gen-rig3.cjs from _reference/all_pose_rigs. Do not edit by hand.\nexport const RIG3_BASE: Record<string, string> = ' + JSON.stringify(out) + ';\nexport const RIG3_CLIPS: Record<string, any> = ' + JSON.stringify(clips) + ';\n');
console.log(Object.keys(clips).length, 'clips', Object.values(out).map((v) => v.length));
