// Builds src/richvrich/data/words.ts (word timings of the whole voice-over) from the ElevenLabs export:   node scripts/make-richvrich-words.cjs "Look Rich Vs Rich/Look_Rich_VS_Rich_eng.json"
const fs = require('fs');
const src = process.argv[2] || 'Look Rich Vs Rich/Look_Rich_VS_Rich_eng.json';
const j = JSON.parse(fs.readFileSync(src, 'utf8'));
const words = j.segments.flatMap((s) => s.words).filter((w) => w.text.trim());
const toks = words.map((w) => [w.text.toLowerCase().replace(/[^a-z0-9]/g, ''), w.start_time, w.end_time]).filter((x) => x[0]);
const lines = [];
for (let i = 0; i < toks.length; i += 12) lines.push(toks.slice(i, i + 12).map((x) => x.join(':')).join(' '));
fs.writeFileSync('src/richvrich/data/words.ts', `// Word timestamps of the whole "Look Rich vs Rich" voice-over (ElevenLabs export, generated by scripts/make-richvrich-words.cjs): word:start:end, lower case, punctuation removed.
const RAW = \`${lines.join('\n')}\`;
export const WORDS_W: [string, number, number][] = RAW.split(/\\s+/).filter(Boolean).map((t) => { const [w, a, b] = t.split(':'); return [w, Number(a), Number(b)]; });
`);
console.log('words', toks.length, 'end', toks[toks.length - 1][2]);
